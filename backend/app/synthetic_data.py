"""
Generates a synthetic, M1-shaped telco customer dataset for a campaign.

This is fabricated data — no real M1 customer records are used or referenced
anywhere in this codebase. Per the proposal's own stated assumption ("all
customer data is synthetic and generated by us") and to keep real customer
PII from ever being sent to a third-party LLM via OpenRouter.

Design note: customers are sampled from a mixture of behavioural archetypes
below, each with its own distribution — a real customer base has natural
density structure (that's *why* clustering finds anything), it isn't
uniformly random. The archetypes exist only to make the generator produce
data with genuine structure; the Segmentation agent's HDBSCAN clustering
still has to discover that structure from the raw features itself — no
archetype label is ever passed to it. `age_bracket` is generated but
deliberately held out of every clustering feature — it exists only so the
Guardian's protected-attribute proxy check (guardian.py) has something real
to test cluster membership against.
"""
