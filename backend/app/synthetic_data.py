def _weighted_choice(rng: random.Random, weights: dict) -> object:
    keys = list(weights.keys())
    probs = list(weights.values())
    return rng.choices(keys, weights=probs, k=1)[0]


def _rand_round(rng: random.Random, lo: float, hi: float, ndigits: int = 2) -> float:
    return round(rng.uniform(lo, hi), ndigits)


@dataclass
class SyntheticCustomer:
    id: str
    campaign_id: str
    structured_attrs: dict
    behavioural: dict
    psychographic: dict
    free_text: str
    consent_state: str


def generate_customer(base_id: str, campaign_id: str, rng: random.Random, archetype: Archetype) -> SyntheticCustomer:
    plan = _weighted_choice(rng, archetype.plan_weights)
    data_tier = _weighted_choice(rng, archetype.data_tier_weights)
    num_lines = _weighted_choice(rng, archetype.num_lines_weights)
    tenure_months = rng.randint(*archetype.tenure_range)
    monthly_spend = _rand_round(rng, *archetype.spend_range)
    roaming_days_90d = rng.choice(archetype.roaming_days_choices)
    device_installment_balance = _rand_round(rng, *archetype.device_balance_range)
    has_5g = rng.random() < archetype.has_5g_prob
    broadband_bundle = rng.random() < archetype.broadband_bundle_prob

    contacts_90d = rng.randint(*archetype.contacts_90d_range)
    app_logins_per_week = rng.randint(*archetype.app_logins_range)
    upgrade_eligibility_days = rng.randint(*archetype.upgrade_eligibility_range)
    promo_open_rate = _rand_round(rng, *archetype.promo_open_rate_range)
    avg_discount_pct = _rand_round(rng, *archetype.avg_discount_range, ndigits=1)
    churn_risk = _rand_round(rng, *archetype.churn_risk_range)
    price_sensitivity = _rand_round(rng, *archetype.price_sensitivity_range)
    tech_enthusiasm = _rand_round(rng, *archetype.tech_enthusiasm_range)
    loyalty_score = _rand_round(rng, *archetype.loyalty_range)

    free_text = rng.choice(archetype.free_text_pool)
    if rng.random() < 0.25:
        free_text += " " + rng.choice(archetype.free_text_pool)

    return SyntheticCustomer(
        id=f"{campaign_id}:{base_id}" if campaign_id else base_id,
        campaign_id=campaign_id,
        structured_attrs={
            "plan_type": plan,
            "data_tier": data_tier,
            "num_lines": num_lines,
            "contract_tenure_months": tenure_months,
            "monthly_spend_sgd": monthly_spend,
            "roaming_days_90d": roaming_days_90d,
            "device_installment_balance_sgd": device_installment_balance,
            "has_5g": has_5g,
            "broadband_bundle": broadband_bundle,
            # Held out — never included in clustering features (see
            # segmentation.py's PROTECTED_ATTRIBUTE_KEYS). Only read back by
            # the Guardian's proxy-correlation check.
            "age_bracket": rng.choice(AGE_BRACKETS),
        },
        behavioural={
            "customer_service_contacts_90d": contacts_90d,
            "app_logins_per_week": app_logins_per_week,
            "upgrade_eligibility_days": upgrade_eligibility_days,
            "promo_email_open_rate": promo_open_rate,
            "avg_discount_at_purchase_pct": avg_discount_pct,
            "churn_risk_score": churn_risk,
        },
        psychographic={
            "price_sensitivity": price_sensitivity,
            "tech_enthusiasm": tech_enthusiasm,
            "loyalty_score": loyalty_score,
        },
        free_text=free_text,
        consent_state="withdrawn" if rng.random() < archetype.consent_withdrawn_prob else "active",
    )


def generate_customers(campaign_id: str, count: int, seed: int = 42) -> list[SyntheticCustomer]:
    """Deterministic — same seed + count always produces the same base
    (same archetype assignments, same attribute values). Kept for scripts/
    tests; the actual app now seeds campaigns from the fixed CSV export of
    this (see load_base_csv / backend/data/m1_synthetic_customers.csv)
    instead of calling this live on every campaign, so the base a marketer
    sees is stable rather than freshly fabricated per run."""
    rng = random.Random(seed)
    archetype_names = [a.name for a in ARCHETYPES]
    archetype_weights = [a.weight for a in ARCHETYPES]
    by_name = {a.name: a for a in ARCHETYPES}

    assignments = rng.choices(archetype_names, weights=archetype_weights, k=count)
    return [
        generate_customer(f"m1-cust-{i:05d}", campaign_id, rng, by_name[name])
        for i, name in enumerate(assignments)
    ]


